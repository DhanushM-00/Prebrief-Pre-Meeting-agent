"""JSON/CSV/Markdown/HTML exporters for research results."""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone
from typing import Any
from xml.sax.saxutils import escape


def research_to_markdown(payload: dict[str, Any]) -> str:
    entity = payload.get("entity_name") or "Subject"
    entity_type = payload.get("entity_type") or ""
    lines = [
        f"# Research Report — {entity}",
        "",
        f"- **Type:** {entity_type}",
        f"- **Window:** {payload.get('window_start', '')[:10]} → {payload.get('window_end', '')[:10]} ({payload.get('window_days')} days)",
        f"- **Depth:** {payload.get('research_depth') or 'standard'}",
        f"- **Generated:** {payload.get('generated_at') or ''}",
        "",
        "## Executive summary",
        "",
        f"{len(payload.get('findings') or [])} findings from {len(payload.get('sources') or [])} sources.",
        "",
    ]
    gaps = payload.get("gaps") or []
    if gaps:
        lines.append("## Gaps")
        lines.append("")
        for g in gaps:
            lines.append(f"- {g}")
        lines.append("")

    lines.append("## Findings")
    lines.append("")
    for f in payload.get("findings") or []:
        if not isinstance(f, dict):
            continue
        conf = f.get("confidence") or ""
        date = f.get("event_date") or ""
        cat = f.get("category") or ""
        lines.append(f"### {f.get('statement')}")
        lines.append(f"- Category: `{cat}` · Confidence: `{conf}` · Date: {date}")
        lines.append("")

    intel = payload.get("company_intelligence") or payload.get("person_intelligence")
    if isinstance(intel, dict):
        lines.append("## Intelligence profile")
        lines.append("")
        for k, v in intel.items():
            if k == "evidence_ids" or not v:
                continue
            if isinstance(v, list):
                lines.append(f"### {k.replace('_', ' ').title()}")
                for item in v:
                    lines.append(f"- {item}")
                lines.append("")
            elif isinstance(v, str):
                lines.append(f"### {k.replace('_', ' ').title()}")
                lines.append(v)
                lines.append("")

    timeline = payload.get("timeline") or []
    if timeline:
        lines.append("## Timeline")
        lines.append("")
        for ev in timeline:
            if isinstance(ev, dict):
                lines.append(
                    f"- **{str(ev.get('date') or '')[:10]}** — {ev.get('title')} "
                    f"({ev.get('category')}, {ev.get('verification_status')})"
                )
        lines.append("")

    oqs = payload.get("open_questions") or []
    if oqs:
        lines.append("## Open questions")
        lines.append("")
        for i, oq in enumerate(oqs, 1):
            if isinstance(oq, dict):
                lines.append(f"{i}. **{oq.get('question')}**")
                if oq.get("rationale"):
                    lines.append(f"   - {oq.get('rationale')}")
        lines.append("")

    lines.append("## Sources")
    lines.append("")
    for i, s in enumerate(payload.get("sources") or [], 1):
        if not isinstance(s, dict):
            continue
        lines.append(f"{i}. **{s.get('headline')}** — {s.get('publisher')} ({str(s.get('published_at') or '')[:10]})")
        if s.get("url"):
            lines.append(f"   - {s.get('url')}")
    lines.append("")
    lines.append("---")
    lines.append("*Generated by PreBrief. Claims without evidence are excluded.*")
    return "\n".join(lines)


def research_to_csv_rows(payload: dict[str, Any]) -> str:
    """CSV of findings with source linkage."""
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(
        [
            "finding_id",
            "category",
            "statement",
            "event_date",
            "confidence",
            "source_ids",
            "entity_name",
            "entity_type",
            "window_start",
            "window_end",
        ]
    )
    entity = payload.get("entity_name") or ""
    etype = payload.get("entity_type") or ""
    ws = payload.get("window_start") or ""
    we = payload.get("window_end") or ""
    for f in payload.get("findings") or []:
        if not isinstance(f, dict):
            continue
        sids = f.get("source_ids") or []
        if not sids and f.get("sources"):
            sids = [s.get("id") for s in f["sources"] if isinstance(s, dict)]
        w.writerow(
            [
                f.get("id") or "",
                f.get("category") or "",
                f.get("statement") or "",
                f.get("event_date") or "",
                f.get("confidence") or "",
                ";".join(str(x) for x in sids),
                entity,
                etype,
                ws,
                we,
            ]
        )
    return buf.getvalue()


def research_to_print_html(payload: dict[str, Any]) -> str:
    entity = escape(str(payload.get("entity_name") or "Subject"))
    entity_type = escape(str(payload.get("entity_type") or ""))
    gen = escape(str(payload.get("generated_at") or ""))
    parts = [
        "<!DOCTYPE html><html><head><meta charset='utf-8'>",
        f"<title>Research — {entity}</title>",
        "<style>",
        "body{font-family:Georgia,serif;max-width:800px;margin:2rem auto;padding:0 1rem;color:#111;line-height:1.5}",
        "h1{font-size:1.6rem} h2{font-size:1.2rem;margin-top:1.6rem;border-bottom:1px solid #ddd;padding-bottom:.3rem}",
        "h3{font-size:1rem;margin-bottom:.2rem} .meta{color:#555;font-size:.9rem}",
        "ul{padding-left:1.2rem} a{color:#1d4ed8} .src{font-size:.85rem;color:#444}",
        "@media print{body{margin:0;max-width:none}}",
        "</style></head><body>",
        f"<h1>Research Report — {entity}</h1>",
        f"<p class='meta'>{entity_type} · window {escape(str(payload.get('window_start') or '')[:10])} → "
        f"{escape(str(payload.get('window_end') or '')[:10])} · generated {gen}</p>",
        f"<p>{len(payload.get('findings') or [])} findings · {len(payload.get('sources') or [])} sources · "
        f"depth {escape(str(payload.get('research_depth') or 'standard'))}</p>",
        "<h2>Findings</h2><ul>",
    ]
    for f in payload.get("findings") or []:
        if not isinstance(f, dict):
            continue
        parts.append(
            f"<li><strong>{escape(str(f.get('statement') or ''))}</strong>"
            f"<div class='src'>{escape(str(f.get('category') or ''))} · "
            f"{escape(str(f.get('confidence') or ''))} · {escape(str(f.get('event_date') or ''))}</div></li>"
        )
    parts.append("</ul>")

    oqs = payload.get("open_questions") or []
    if oqs:
        parts.append("<h2>Open questions</h2><ol>")
        for oq in oqs:
            if isinstance(oq, dict):
                parts.append(f"<li><strong>{escape(str(oq.get('question') or ''))}</strong>")
                if oq.get("rationale"):
                    parts.append(f"<div class='src'>{escape(str(oq.get('rationale')))}</div>")
                parts.append("</li>")
        parts.append("</ol>")

    parts.append("<h2>Sources</h2><ol>")
    for s in payload.get("sources") or []:
        if not isinstance(s, dict):
            continue
        url = escape(str(s.get("url") or ""))
        parts.append(
            f"<li><strong>{escape(str(s.get('headline') or ''))}</strong> — "
            f"{escape(str(s.get('publisher') or ''))}"
            f"{f' · <a href=\"{url}\">{url}</a>' if url else ''}</li>"
        )
    parts.append("</ol>")
    parts.append("<p class='meta'>Generated by PreBrief. No claims without evidence.</p>")
    parts.append("</body></html>")
    return "\n".join(parts)
